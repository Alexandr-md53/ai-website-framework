#: languages the admin panel itself is translated into (shop content languages
#: are separate and configured as data)
ADMIN_LANGUAGES: Tuple[str, ...] = ("ru", "ro", "en")

#: display titles for the admin language switcher
ADMIN_LANGUAGE_TITLES: Dict[str, str] = {
    "ru": "Русский",
    "ro": "Română",
    "en": "English",
}


def admin_language_choices() -> Tuple[Tuple[str, str], ...]:
    """``(code, title)`` pairs for the admin UI switcher."""
    return tuple((code, ADMIN_LANGUAGE_TITLES.get(code, code)) for code in ADMIN_LANGUAGES)


def get_ui(lang: str, fallback: str = "en") -> Dict:
    """Return the UI strings for ``lang``, falling back to ``fallback``."""
    return UI.get((lang or "").lower()) or UI.get(fallback) or UI["en"]


def get_admin_ui(requested: str, shop_default: str = "") -> Tuple[str, Dict]:
    """Resolve the admin UI language independently of the shop's languages.

    Any of RU/RO/EN always works in the admin panel, so the interface can be
    switched even when the shop itself is configured with a single language.
    """
    candidate = (requested or "").strip().lower()
    if candidate in ADMIN_LANGUAGES:
        return candidate, UI[candidate]
    fallback = (shop_default or "").strip().lower()
    if fallback in ADMIN_LANGUAGES:
        return fallback, UI[fallback]
    return "en", UI["en"]
